-- ---------------------------------------------------------------------
-- 005 — 측정 온·습도의 소수 자릿수를 두 자리로 넓힌다.
--
-- 왜:
--   SCD41 은 0.01℃ 단위로 값을 주는데 sensor_env.temperature 가
--   numeric(4,1) 이라 0.1℃ 로 잘려 저장되고 있었다. 20x20x30cm(12L)
--   목업에서 재실자 1명 상당의 열부하(약 0.36W)가 30분에 만드는 변화는
--   약 0.22℃ 다. 0.1℃ 눈금에서는 두 칸이라 잡음과 구분되지 않는다.
--   두 자리로 늘리면 같은 실험이 22칸으로 잡혀 RC 열모델(a, b, d)
--   식별이 가능해진다.
--
--   설정값(rooms.target_temp 등)은 사람이 정하는 값이므로 0.1℃ 로 둔다.
--   이 마이그레이션이 건드리는 것은 '측정값' 뿐이다.
--
-- 안전성:
--   numeric(4,1) -> numeric(5,2) 는 정밀도를 넓히기만 하므로 기존 값은
--   그대로 유지된다(24.6 -> 24.60). 되돌릴 필요가 생기면 컬럼을
--   numeric(4,1) 로 되돌리면 되지만, 그 시점 이후 쌓인 소수 둘째 자리는
--   반올림되어 사라진다.
-- ---------------------------------------------------------------------

ALTER TABLE sensor_env
    ALTER COLUMN temperature TYPE numeric(5,2),
    ALTER COLUMN humidity    TYPE numeric(5,2);
